-- NBA DATA WAREHOUSE PROJECT
-- Database and schema setup

CREATE DATABASE IF NOT EXISTS NBA_DATA_WAREHOUSE;
CREATE SCHEMA IF NOT EXISTS NBA_DATA_WAREHOUSE.RAW;
CREATE SCHEMA IF NOT EXISTS NBA_DATA_WAREHOUSE.STAGING;
CREATE SCHEMA IF NOT EXISTS NBA_DATA_WAREHOUSE.DW;

USE WAREHOUSE COMPUTE_WH;
USE DATABASE NBA_DATA_WAREHOUSE;
USE SCHEMA RAW;

CREATE TABLE IF NOT EXISTS NBA_PLAYERS_API (
    PLAYER_ID NUMBER,
    FIRST_NAME VARCHAR(100),
    LAST_NAME VARCHAR(100),
    POSITION VARCHAR(20),
    TEAM_ID NUMBER,
    TEAM_NAME VARCHAR(100),
    JERSEY_NUMBER VARCHAR(10),
    HEIGHT VARCHAR(20),
    WEIGHT VARCHAR(20),
    COLLEGE VARCHAR(150),
    COUNTRY VARCHAR(100),
    DRAFT_YEAR NUMBER,
    DRAFT_ROUND NUMBER,
    DRAFT_NUMBER NUMBER,
    EXTRACTION_TIMESTAMP TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    SOURCE_SYSTEM VARCHAR(50) DEFAULT 'BALLDONTLIE'
);

CREATE TABLE IF NOT EXISTS NBA_DATA_WAREHOUSE.DW.DIM_NBA_PLAYERS (
    PLAYER_KEY NUMBER AUTOINCREMENT START 1 INCREMENT 1,
    PLAYER_ID NUMBER NOT NULL,
    FIRST_NAME VARCHAR(100),
    LAST_NAME VARCHAR(100),
    POSITION VARCHAR(20),
    TEAM_ID NUMBER,
    TEAM_NAME VARCHAR(100),
    JERSEY_NUMBER VARCHAR(10),
    HEIGHT VARCHAR(20),
    WEIGHT VARCHAR(20),
    COLLEGE VARCHAR(150),
    COUNTRY VARCHAR(100),
    DRAFT_YEAR NUMBER,
    DRAFT_ROUND NUMBER,
    DRAFT_NUMBER NUMBER,
    START_DATE DATE NOT NULL,
    END_DATE DATE NOT NULL,
    IS_CURRENT BOOLEAN NOT NULL,
    HASH_DIFF VARCHAR(64),
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);
