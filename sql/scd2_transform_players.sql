-- SCD2 transform: STAGING.STG_NBA_PLAYERS -> DW.DIM_NBA_PLAYERS

USE DATABASE NBA_DATA_WAREHOUSE;
USE SCHEMA DW;

-- 1. Build the source snapshot and calculate the change hash.
CREATE OR REPLACE TEMPORARY TABLE TMP_NBA_PLAYERS_SCD2 AS
SELECT
    PLAYER_ID,
    FIRST_NAME,
    LAST_NAME,
    POSITION,
    TEAM_ID,
    TEAM_NAME,
    JERSEY_NUMBER,
    HEIGHT,
    WEIGHT,
    COLLEGE,
    COUNTRY,
    DRAFT_YEAR,
    DRAFT_ROUND,
    DRAFT_NUMBER,
    MD5(CONCAT_WS('|',
        COALESCE(FIRST_NAME, ''),
        COALESCE(LAST_NAME, ''),
        COALESCE(POSITION, ''),
        COALESCE(TO_VARCHAR(TEAM_ID), ''),
        COALESCE(TEAM_NAME, ''),
        COALESCE(JERSEY_NUMBER, ''),
        COALESCE(HEIGHT, ''),
        COALESCE(WEIGHT, ''),
        COALESCE(COLLEGE, ''),
        COALESCE(COUNTRY, ''),
        COALESCE(TO_VARCHAR(DRAFT_YEAR), ''),
        COALESCE(TO_VARCHAR(DRAFT_ROUND), ''),
        COALESCE(TO_VARCHAR(DRAFT_NUMBER), '')
    )) AS HASH_DIFF,
    COALESCE(TO_DATE(EXTRACTION_TIMESTAMP), CURRENT_DATE()) AS EFFECTIVE_DATE
FROM NBA_DATA_WAREHOUSE.STAGING.STG_NBA_PLAYERS;

-- 2. Close current dimension rows that changed or disappeared.
UPDATE NBA_DATA_WAREHOUSE.DW.DIM_NBA_PLAYERS AS dim
SET
    END_DATE = CURRENT_DATE(),
    IS_CURRENT = FALSE,
    UPDATED_AT = CURRENT_TIMESTAMP()
WHERE dim.IS_CURRENT = TRUE
  AND (
      NOT EXISTS (
          SELECT 1
          FROM TMP_NBA_PLAYERS_SCD2 src
          WHERE src.PLAYER_ID = dim.PLAYER_ID
      )
      OR EXISTS (
          SELECT 1
          FROM TMP_NBA_PLAYERS_SCD2 src
          WHERE src.PLAYER_ID = dim.PLAYER_ID
            AND src.HASH_DIFF <> dim.HASH_DIFF
      )
  );

-- 3. Insert a new dimension row for new or changed players.
MERGE INTO NBA_DATA_WAREHOUSE.DW.DIM_NBA_PLAYERS AS dim
USING TMP_NBA_PLAYERS_SCD2 AS src
ON dim.PLAYER_ID = src.PLAYER_ID
   AND dim.IS_CURRENT = TRUE
   AND dim.HASH_DIFF = src.HASH_DIFF
WHEN NOT MATCHED THEN
    INSERT (
        PLAYER_ID, FIRST_NAME, LAST_NAME, POSITION, TEAM_ID, TEAM_NAME,
        JERSEY_NUMBER, HEIGHT, WEIGHT, COLLEGE, COUNTRY,
        DRAFT_YEAR, DRAFT_ROUND, DRAFT_NUMBER,
        START_DATE, END_DATE, IS_CURRENT, HASH_DIFF,
        CREATED_AT, UPDATED_AT
    )
    VALUES (
        src.PLAYER_ID, src.FIRST_NAME, src.LAST_NAME, src.POSITION,
        src.TEAM_ID, src.TEAM_NAME, src.JERSEY_NUMBER, src.HEIGHT,
        src.WEIGHT, src.COLLEGE, src.COUNTRY,
        src.DRAFT_YEAR, src.DRAFT_ROUND, src.DRAFT_NUMBER,
        src.EFFECTIVE_DATE, '9999-12-31'::DATE, TRUE, src.HASH_DIFF,
        CURRENT_TIMESTAMP(), CURRENT_TIMESTAMP()
    );

-- 4. Validate the result.
SELECT
    COUNT(*) AS TOTAL_VERSION_ROWS,
    SUM(IFF(IS_CURRENT, 1, 0)) AS CURRENT_ROWS,
    COUNT(DISTINCT PLAYER_ID) AS DISTINCT_PLAYERS
FROM NBA_DATA_WAREHOUSE.DW.DIM_NBA_PLAYERS;
