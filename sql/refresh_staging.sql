-- Refresh staging with the latest record for every player in RAW.

CREATE OR REPLACE TABLE NBA_DATA_WAREHOUSE.STAGING.STG_NBA_PLAYERS AS
WITH ranked_players AS (
    SELECT
        PLAYER_ID,
        FIRST_NAME,
        LAST_NAME,
        POSITION,
        TEAM_ID,
        TEAM_NAME,
        JERSEY_NUMBER,
        HEIGHT,
        WEIGHT,
        COLLEGE,
        COUNTRY,
        DRAFT_YEAR,
        DRAFT_ROUND,
        DRAFT_NUMBER,
        EXTRACTION_TIMESTAMP,
        SOURCE_SYSTEM,
        ROW_NUMBER() OVER (
            PARTITION BY PLAYER_ID
            ORDER BY EXTRACTION_TIMESTAMP DESC
        ) AS RECORD_RANK
    FROM NBA_DATA_WAREHOUSE.RAW.NBA_PLAYERS_API
)
SELECT
    PLAYER_ID,
    FIRST_NAME,
    LAST_NAME,
    NULLIF(TRIM(POSITION), '') AS POSITION,
    TEAM_ID,
    NULLIF(TRIM(TEAM_NAME), '') AS TEAM_NAME,
    NULLIF(TRIM(JERSEY_NUMBER), '') AS JERSEY_NUMBER,
    NULLIF(TRIM(HEIGHT), '') AS HEIGHT,
    NULLIF(TRIM(WEIGHT), '') AS WEIGHT,
    NULLIF(TRIM(COLLEGE), '') AS COLLEGE,
    NULLIF(TRIM(COUNTRY), '') AS COUNTRY,
    DRAFT_YEAR,
    DRAFT_ROUND,
    DRAFT_NUMBER,
    EXTRACTION_TIMESTAMP,
    SOURCE_SYSTEM
FROM ranked_players
WHERE RECORD_RANK = 1;

SELECT COUNT(*) AS STAGING_PLAYER_COUNT
FROM NBA_DATA_WAREHOUSE.STAGING.STG_NBA_PLAYERS;
